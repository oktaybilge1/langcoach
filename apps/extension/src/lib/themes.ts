function toUiLocale(uiLang: string): UiLocale {
  const norm = String(uiLang ?? '')
    .trim()
    .toLowerCase();
  if (norm.startsWith('tr')) return 'tr';
  if (norm.startsWith('es')) return 'es';
  if (norm.startsWith('fr')) return 'fr';
  if (norm.startsWith('pt')) return 'pt_BR';
  return 'en';
}

